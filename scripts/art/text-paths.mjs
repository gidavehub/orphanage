// Outline display words to SVG paths (Anton) for masks/knockouts.
// Paths aren't LCP candidates and don't depend on the webfont loading inside an SVG mask.
//   node scripts/art/text-paths.mjs  → components/art/manifesto-glyphs.ts
import opentype from "opentype.js";
import { readFile, writeFile } from "fs/promises";

const buf = await readFile("assets/fonts/Anton-Regular.ttf");
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const SIZE = 330;
const TRACK = -3 / SIZE; // letterSpacing −3 units at this size, in em
const line = (text, baseline) => {
  const opts = { kerning: true, letterSpacing: TRACK };
  const width = font.getAdvanceWidth(text, SIZE, opts);
  const p = font.getPath(text, 500 - width / 2, baseline, SIZE, opts);
  return p.toPathData(1);
};
const out = {
  every: line("EVERY", 306),
  child: line("CHILD", 618),
};
await writeFile(
  "components/art/manifesto-glyphs.ts",
  "// AUTO-GENERATED by scripts/art/text-paths.mjs (Anton outlines in a 1000×640 box). Do not edit.\n\n" +
    `export const manifestoGlyphs = ${JSON.stringify(out, null, 2)} as const;\n`,
);
console.log("ok", Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.length])));
