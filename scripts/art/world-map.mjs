// Bake the dotted world map behind "One Family, Every Nation".
//
//   node scripts/art/world-map.mjs
//
// Natural Earth land (world-atlas 110m), Antarctica dropped, Equal Earth projection.
// → public/art/world-dots.svg: land as one path of zero-length segments ("M x y h0") with
//   round caps, so one <path> draws every dot (a lazy <img>, kept out of the HTML payload).
// → components/art/world-map.ts: viewBox size + projected marker positions from
//   content/world.ts (lat/lon), rendered inline as the interactive marker layer.

import { mkdir, readFile, writeFile } from "fs/promises";
import { feature } from "topojson-client";
import { geoContains, geoEqualEarth } from "d3-geo";
import { countries } from "../../content/world.ts";

const W = 1000;
const H = 470;
const STEP = 7.5; // dot pitch in viewBox units

const topo = JSON.parse(await readFile("node_modules/world-atlas/land-110m.json", "utf8"));
const land = feature(topo, topo.objects.land);
// Drop Antarctica: keep polygons with any point north of 60°S.
land.features[0].geometry.coordinates = land.features[0].geometry.coordinates.filter((poly) => poly[0].some(([, lat]) => lat > -60));

const projection = geoEqualEarth().fitExtent([[6, 6], [W - 6, H - 6]], land);

const dots = [];
for (let y = STEP / 2; y < H; y += STEP) {
  // Offset alternate rows by half a step for an even, woven texture.
  const shift = (Math.round(y / STEP) % 2) * (STEP / 2);
  for (let x = STEP / 2 + shift; x < W; x += STEP) {
    const ll = projection.invert([x, y]);
    if (ll && geoContains(land, ll)) dots.push(`M${x.toFixed(1)} ${y.toFixed(1)}h0`);
  }
}

const points = Object.fromEntries(
  countries.map(({ code, lat, lon }) => {
    const [x, y] = projection([lon, lat]);
    return [code, [Math.round(x * 10) / 10, Math.round(y * 10) / 10]];
  }),
);

// Dots in the brand cocoa (#7b4a2b) at low opacity, matching the paper section behind them.
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}"><path d="${dots.join("")}" fill="none" stroke="#7b4a2b" stroke-opacity="0.3" stroke-width="5" stroke-linecap="round"/></svg>`;
await mkdir("public/art", { recursive: true });
await writeFile("public/art/world-dots.svg", svg);

const out = `// AUTO-GENERATED by scripts/art/world-map.mjs (world-atlas land-110m, Equal Earth). Do not edit.

export const worldMap = {
  width: ${W},
  height: ${H},
  /** Dotted land layer (static file, same viewBox). */
  dots: "/art/world-dots.svg",
  /** Projected marker position per ISO code in content/world.ts. */
  points: ${JSON.stringify(points)} as Record<string, [number, number]>,
} as const;
`;
await writeFile("components/art/world-map.ts", out);
console.log(`  ✓ public/art/world-dots.svg: ${dots.length} land dots (${(svg.length / 1024).toFixed(0)} KB)`);
console.log(`  ✓ components/art/world-map.ts: ${Object.keys(points).length} markers (${(out.length / 1024).toFixed(1)} KB)`);
