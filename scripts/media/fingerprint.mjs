// Content-hash every published media file and regenerate content/media-map.ts.
//
//   node scripts/media/fingerprint.mjs
//
// `story-2.webp` → `story-2.1a2b3c4d.webp`. A replaced image gets a brand-new URL, so no
// cache can serve the old picture: not the browser, not a CDN, and not Next's image
// optimizer (which caches by URL for ≥ 4 hours and has no invalidation). process.mjs and
// stitch.mjs call this automatically; lib/media/pipeline.ts resolves ids through the map.

import { createHash } from "crypto";
import { readdir, readFile, rename, stat, unlink, writeFile } from "fs/promises";
import path from "path";

const KINDS = {
  img: { dir: "public/media/img", ext: "webp" },
  video: { dir: "public/media/video", ext: "mp4" },
  poster: { dir: "public/media/posters", ext: "webp" },
};
const HASHED = /^(.+)\.([0-9a-f]{8})\.(webp|mp4)$/;

/** True when `id` is already published in `dir`, hashed or not (lets process.mjs skip work). */
export async function hasAsset(dir, id, ext) {
  const files = await readdir(dir).catch(() => []);
  return files.some((f) => f === `${id}.${ext}` || (HASHED.exec(f)?.[1] === id && f.endsWith(`.${ext}`)));
}

export async function fingerprint({ quiet = false } = {}) {
  const map = {};
  let renamed = 0;
  for (const [kind, { dir, ext }] of Object.entries(KINDS)) {
    map[kind] = {};
    const files = await readdir(dir);

    // Fresh plain files replace any hashed version of the same id.
    for (const f of files.filter((f) => f.endsWith(`.${ext}`) && !HASHED.test(f))) {
      const id = f.slice(0, -(ext.length + 1));
      const buf = await readFile(path.join(dir, f));
      const hash = createHash("sha1").update(buf).digest("hex").slice(0, 8);
      for (const old of files.filter((o) => HASHED.exec(o)?.[1] === id)) await unlink(path.join(dir, old)).catch(() => {});
      await rename(path.join(dir, f), path.join(dir, `${id}.${hash}.${ext}`));
      renamed++;
    }

    // One hashed file per id (newest wins).
    const hashed = (await readdir(dir)).filter((f) => HASHED.test(f) && f.endsWith(`.${ext}`));
    const newest = {};
    for (const f of hashed) {
      const id = HASHED.exec(f)[1];
      const t = (await stat(path.join(dir, f))).mtimeMs;
      if (!newest[id] || t > newest[id].t) {
        if (newest[id]) await unlink(path.join(dir, newest[id].f));
        newest[id] = { f, t };
      } else await unlink(path.join(dir, f));
    }
    const sub = dir.replace(/^public/, "");
    for (const id of Object.keys(newest).sort()) map[kind][id] = `${sub}/${newest[id].f}`;
  }

  const out = `// AUTO-GENERATED by scripts/media/fingerprint.mjs: content-hashed media URLs. Do not edit.
// Ids resolve through img() / video() / poster() in lib/media/pipeline.ts.

export const mediaMap: Record<"img" | "video" | "poster", Record<string, string>> = ${JSON.stringify(map, null, 2)};
`;
  await writeFile("content/media-map.ts", out);
  if (!quiet) {
    const n = Object.values(map).reduce((a, m) => a + Object.keys(m).length, 0);
    console.log(`  ✓ fingerprinted ${renamed} new file(s); content/media-map.ts lists ${n}`);
  }
  return map;
}

if (import.meta.url === `file:///${process.argv[1].replace(/\\/g, "/")}`) await fingerprint();
