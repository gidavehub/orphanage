// Trace the generated ink brush plates into SVG path data for masks/edges.
//
//   node scripts/media/trace-brushes.mjs   → public/brush/<name>.svg + components/art/brush-index.ts
//
// Each plate is thresholded, downscaled (keeps bristle character while holding path
// size down), traced with potrace and written as a static SVG. <Brush> applies them
// as CSS masks, so one shape can take any colour or mask a photo, and nothing lands
// in the JS bundle.

import sharp from "sharp";
import potrace from "potrace";
import { writeFile, access, mkdir } from "fs/promises";
import path from "path";
import { images } from "./manifest.mjs";

const RAW = path.resolve("media-src/raw");
const OUT_DIR = path.resolve("public/brush");
const INDEX = path.resolve("components/art/brush-index.ts");
const exists = (p) => access(p).then(() => true, () => false);

const LONG_SIDE = { "brush-band": 1400, "brush-torn": 1400 };

function trace(buf, opts) {
  return new Promise((resolve, reject) =>
    potrace.trace(buf, opts, (err, svg) => (err ? reject(err) : resolve(svg))),
  );
}

await mkdir(OUT_DIR, { recursive: true });
const plates = images.filter((s) => s.kind === "brush");
const entries = [];
for (const p of plates) {
  const src = path.join(RAW, `${p.id}.png`);
  if (!(await exists(src))) {
    console.log(`  · ${p.id}: missing plate`);
    continue;
  }
  const long = LONG_SIDE[p.id] ?? 820;
  const { data, info } = await sharp(src)
    .flatten({ background: "#ffffff" })
    .grayscale()
    .resize({ width: long, height: long, fit: "inside" })
    .normalise()
    .threshold(150)
    .png()
    .toBuffer({ resolveWithObject: true });
  const svg = await trace(data, { threshold: 128, turdSize: 24, optTolerance: 0.7, alphaMax: 1.15, color: "#000" });
  const ds = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
  const d = ds.join(" ").replace(/\s+/g, " ").replace(/(\d+)\.\d+/g, "$1").trim();
  const name = p.id.replace(/^brush-/, "");
  const file = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${info.width} ${info.height}" preserveAspectRatio="none"><path fill="#000" fill-rule="evenodd" d="${d}"/></svg>`;
  await writeFile(path.join(OUT_DIR, `${name}.svg`), file);
  entries.push({ name, w: info.width, h: info.height });
  console.log(`  ✓ ${name.padEnd(8)} ${info.width}×${info.height}  ${(file.length / 1024).toFixed(1)} KB`);
}

const body = [
  "// AUTO-GENERATED by scripts/media/trace-brushes.mjs from Optiq-generated ink plates. Do not edit.",
  "",
  "export const brushes = {",
  ...entries.map((e) => `  ${JSON.stringify(e.name)}: { w: ${e.w}, h: ${e.h} },`),
  "} as const;",
  "",
  "export type BrushName = keyof typeof brushes;",
  "",
].join("\n");
await writeFile(INDEX, body);
console.log(`\n  wrote ${INDEX}`);
